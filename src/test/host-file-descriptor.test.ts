import assert from "node:assert/strict";
import { test } from "node:test";
import { HostDescriptor } from "../host/descriptor.js";
import { FdTable } from "../core/fd.js";
import { HostInode } from "../host/inode.js";
import { HostProcess } from "../host/process.js";
import { mountedKernel } from "./vfs-fixture.js";
import { withImage } from "../host/native-access.js";
import { THISTLE_FD_READ, THISTLE_FD_WRITE, THISTLE_FD_APPEND, THISTLE_FD_CLOEXEC } from "../native/abi.js";
import { thistleReadDescriptor, thistleCloseDescriptor, thistleHartInit, thistleProcessInit } from "../native/kernel.js";

test("host inode descriptors share native reads and survive unlink", () => {
  const memory = mountedKernel(), process = new HostProcess(memory, 0);
  const root = HostInode.resolve(process, "/"), file = root.create(process, "file", 1, 0o600);
  file.write(process, Uint8Array.of(1, 2, 3), 0, true);
  const fd = HostDescriptor.open(process, file, THISTLE_FD_READ);
  assert.equal(fd.inode, file.ino);
  const table = new FdTable(process), view = table.get(fd.number);
  assert.ok(view);
  assert.equal(view.inode, file.ino);
  assert.ok(table.keys().includes(fd.number));
  root.unlink(process, "file");
  withImage(memory, 3, input => {
    assert.equal(thistleReadDescriptor(memory, 0, fd.number, input, 2), 2);
    assert.deepEqual([...memory.bytes.subarray(input, input + 2)], [1, 2]);
  });
  assert.equal(fd.offset, 2);
  assert.equal(view.pos, 2);
  assert.equal(thistleCloseDescriptor(memory, 0, fd.number), 0);
  assert.throws(() => fd.offset, { code: "EBADF" });
  assert.equal(table.get(fd.number), null);
  assert.throws(() => file.metadata(), { code: "ENOENT" });
  const replacement = root.create(process, "new", 1, 0o600);
  replacement.write(process, Uint8Array.of(4, 5), 0, true);
  const append = HostDescriptor.open(process, replacement, THISTLE_FD_WRITE | THISTLE_FD_APPEND);
  assert.equal(append.number, fd.number);
  assert.equal(append.offset, 2);
  assert.throws(() => fd.flags, { code: "EBADF" });
  append.close();
  assert.throws(() => HostDescriptor.open(process, root, THISTLE_FD_WRITE), { code: "EISDIR" });
});

test("native file descriptor writes and seeks preserve access after unlink and chmod", () => {
  const memory = mountedKernel(), process = new HostProcess(memory, 0);
  const root = HostInode.resolve(process, "/"), file = root.create(process, "file", 1, 0o600);
  file.write(process, Uint8Array.of(1, 2, 3), 0, true);
  const fd = HostDescriptor.open(process, file, THISTLE_FD_READ | THISTLE_FD_WRITE);
  const append = HostDescriptor.open(process, file, THISTLE_FD_WRITE | THISTLE_FD_APPEND);
  file.chmod(process, 0);
  root.unlink(process, "file");
  assert.equal(fd.seekFile(1, 0), 1);
  assert.equal(fd.writeFile(Uint8Array.of(9)), 1);
  assert.equal(fd.offset, 2);
  assert.equal(append.seekFile(0, 0), 0);
  assert.equal(append.writeFile(Uint8Array.of(4)), 1);
  assert.equal(append.offset, 4);
  assert.equal(fd.seekFile(0, 0), 0);
  assert.deepEqual([...fd.readFile(8)], [1, 9, 3, 4]);
  assert.throws(() => append.readFile(1), { code: "EBADF" });
  assert.throws(() => fd.seekFile(-5, 0), { code: "EINVAL" });
  assert.equal(fd.offset, 4);
  append.close();
  assert.equal(file.metadata().nlink, 0);
  fd.close();
  assert.throws(() => file.metadata(), { code: "ENOENT" });
});

test("descriptor inheritance retains unlinked inodes across processes", () => {
  const memory = mountedKernel(2), parent = new HostProcess(memory, 0);
  assert.equal(thistleHartInit(memory, 1, 0x10000000n, 0n), 0);
  assert.equal(thistleProcessInit(memory, 1, 2, 1, 1000, 1000, 1000, 1000, 1000, 1000), 0);
  const child = new HostProcess(memory, 1);
  const root = HostInode.resolve(parent, "/"), file = root.create(parent, "secret", 1, 0o600);
  file.write(parent, Uint8Array.of(1, 2, 3), 0, true);
  const fd = HostDescriptor.open(parent, file, THISTLE_FD_READ | THISTLE_FD_CLOEXEC);
  assert.deepEqual([...fd.readFile(1)], [1]);
  root.unlink(parent, "secret");
  const source = new FdTable(parent), target = new FdTable(child);
  const view = source.get(fd.number);
  assert.ok(view);
  target.inherit(7, view, false);
  const inherited = target.get(7);
  assert.ok(inherited);
  assert.equal(inherited.inode, file.ino);
  assert.equal(inherited.clo, false);
  assert.equal(inherited.pos, 1);
  fd.close();
  assert.deepEqual([...inherited.readFile(2)], [2, 3]);
  assert.throws(() => target.inherit(8, view), { code: "EBADF" });
  target.delete(7);
  assert.throws(() => file.metadata(), { code: "ENOENT" });
});

test("opened directories retain identity across rename and permission changes", () => {
  const memory = mountedKernel(2), root = new HostProcess(memory, 0);
  const directory = HostInode.resolve(root, "/");
  const work = directory.create(root, "work", 2, 0o755);
  const file = work.create(root, "entry", 1, 0o644);
  assert.equal(thistleHartInit(memory, 1, 0x10000000n, 0n), 0);
  assert.equal(thistleProcessInit(memory, 1, 2, 1, 1000, 1000, 1000, 1000, 1000, 1000), 0);
  const user = new HostProcess(memory, 1);
  const fd = HostDescriptor.openPath(user, "/work", 0x10000);
  directory.rename(root, "work", directory, "renamed");
  work.chmod(root, 0);
  const view = new FdTable(user).get(fd.number);
  assert.ok(view);
  const inode = view.inodeView();
  assert.ok(inode);
  assert.equal(inode.identity, work.identity);
  assert.deepEqual(view.directoryEntries(), [{ name: "entry", inode: file.ino, kind: 1 }]);
  assert.throws(() => HostDescriptor.openPath(user, "/renamed", 0x10000), { code: "EACCES" });
  fd.close();
});
