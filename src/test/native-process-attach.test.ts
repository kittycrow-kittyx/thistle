import assert from "node:assert/strict";
import { test } from "node:test";
import { mountedKernel } from "./vfs-fixture.js";
import { C_PROCESS_COUNT, C_PROCESS_LOCK, H_LOCK, THISTLE_HART_BASE, THISTLE_HART_STRIDE } from "../native/abi.js";
import { loadU32, storeU32 } from "../native/memory.js";
import { thistleHartInit, thistleProcessInit, thistleGuestPage, thistleExitHart, thistleProcessReap, thistleHartVirtualTop } from "../native/kernel.js";
import { thistleProcessAttach, thistleProcessRecord, thistleProcessSetGroup } from "../native/process-state.js";
import { readGroup } from "../native/credentials.js";

test("attaching another hart shares the existing canonical process and pages", () => {
  const memory = mountedKernel(3);
  assert.equal(thistleHartInit(memory, 1, 0x10000000n, 0n), 0);
  assert.equal(thistleProcessInit(memory, 1, 2, 1, 1000, 1000, 1000, 100, 100, 100), 0);
  const proc = thistleProcessRecord(memory, 1);
  const page = thistleGuestPage(memory, 1, 0x10000n, true);
  memory.bytes[page] = 42;
  assert.equal(thistleProcessAttach(memory, 2, 2), -22);
  assert.equal(thistleHartInit(memory, 2, 0x20000000n, 0n), 0);
  const leaderLock = THISTLE_HART_BASE + THISTLE_HART_STRIDE + H_LOCK;
  storeU32(memory, leaderLock, 1);
  assert.equal(thistleProcessAttach(memory, 2, 2), -11);
  assert.equal(thistleProcessRecord(memory, 2), 0xffffffff);
  storeU32(memory, leaderLock, 0);
  storeU32(memory, C_PROCESS_LOCK, 1);
  assert.equal(thistleProcessAttach(memory, 2, 2), -11);
  storeU32(memory, C_PROCESS_LOCK, 0);
  assert.equal(thistleProcessAttach(memory, 2, 9999), -3);
  assert.equal(thistleProcessAttach(memory, 2, 2), 0);
  assert.equal(thistleProcessRecord(memory, 2), proc);
  assert.equal(loadU32(memory, C_PROCESS_COUNT), 2);
  assert.equal(thistleHartVirtualTop(memory, 2), 0x10000000n);
  assert.equal(thistleGuestPage(memory, 2, 0x10000n, false), page);
  assert.equal(memory.view.getUint8(page), 42);
  assert.equal(thistleProcessSetGroup(memory, 1, 0, 1234), 0);
  assert.equal(readGroup(memory, thistleProcessRecord(memory, 2), 0), 1234);
  assert.equal(thistleProcessAttach(memory, 2, 1), -16);
  assert.equal(thistleProcessRecord(memory, 2), proc);
  assert.equal(thistleExitHart(memory, 2, 0), 0);
  assert.equal(thistleProcessReap(memory, 0, 2), -11);
  assert.equal(thistleExitHart(memory, 1, 0), 0);
  assert.equal(thistleProcessReap(memory, 0, 2), 0);
  assert.equal(loadU32(memory, C_PROCESS_COUNT), 1);
});
